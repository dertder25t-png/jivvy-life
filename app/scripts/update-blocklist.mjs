#!/usr/bin/env node
// Converts EasyPrivacy + EasyList into a WebKit content-rule JSON (committed; the app never
// downloads lists at runtime). No dependencies. Review the git diff before committing.
import { createHash } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCES = [
  'https://easylist.to/easylist/easyprivacy.txt',
  'https://easylist.to/easylist/easylist.txt',
]
const MAX_BYTES = 20 * 1024 * 1024
const MAX_RULES = 120000
const DOMAIN_RE = /^(?=.{1,253}$)([a-z0-9-]{1,63}\.)+[a-z]{2,63}$/
const NEVER_BLOCK = [
  'instructure.com', 'pcci.edu', 'canvas-user-content.com', 'google.com', 'gstatic.com',
  'googleapis.com', 'accounts.google.com', 'login.microsoftonline.com', 'microsoftonline.com',
  'live.com', 'okta.com', 'duosecurity.com', 'github.com', 'githubusercontent.com',
]
const DOWNLOAD_DATE = '2026-11-18'

async function download(url) {
  if (!url.startsWith('https://')) throw new Error('HTTPS only: ' + url)
  const res = await fetch(url, { redirect: 'error' })
  if (res.status !== 200) throw new Error(`${url}: HTTP ${res.status}`)
  const len = Number(res.headers.get('content-length') || 0)
  if (len > MAX_BYTES) throw new Error(`${url}: too large`)
  const chunks = []
  let total = 0
  for await (const c of res.body) {
    total += c.length
    if (total > MAX_BYTES) throw new Error(`${url}: body exceeds 20 MB`)
    chunks.push(c)
  }
  return Buffer.concat(chunks).toString('utf8')
}

const escDomain = (d) => d.replace(/\./g, '\\.')
const filterFor = (d) => `^[^:]+://+([^:/]+\\.)?${escDomain(d)}[:/]`

function parse(text, blocks, excepts) {
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim()
    let m = /^@@\|\|([^\s$^*/|]+)\^$/.exec(line)
    if (m) {
      const d = m[1].toLowerCase()
      if (DOMAIN_RE.test(d)) excepts.add(d)
      continue
    }
    m = /^\|\|([^\s$^*/|]+)\^(\$third-party)?$/.exec(line)
    if (m) {
      const d = m[1].toLowerCase()
      if (DOMAIN_RE.test(d)) blocks.add(d)
    }
  }
}

const blocks = new Set()
const excepts = new Set()
const bodies = []
for (const url of SOURCES) bodies.push(await download(url))
for (const b of bodies) parse(b, blocks, excepts)

const hard = new Set(NEVER_BLOCK)
const hardRules = NEVER_BLOCK.map((d) => ({
  trigger: { 'url-filter': filterFor(d) },
  action: { type: 'ignore-previous-rules' },
}))
const exceptList = [...excepts].filter((d) => !hard.has(d))
const reserved = exceptList.length + hardRules.length
const blockList = [...blocks].filter((d) => !hard.has(d)).slice(0, Math.max(0, MAX_RULES - reserved))
const rules = [
  ...blockList.map((d) => ({
    trigger: { 'url-filter': filterFor(d), 'load-type': ['third-party'] },
    action: { type: 'block' },
  })),
  ...exceptList.map((d) => ({
    trigger: { 'url-filter': filterFor(d) },
    action: { type: 'ignore-previous-rules' },
  })),
  ...hardRules,
]
if (rules.length > MAX_RULES) throw new Error('rule cap exceeded')

const json = JSON.stringify(rules)
JSON.parse(json)
const sha = createHash('sha256').update(json).digest('hex')
const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src-tauri', 'blocklist')
mkdirSync(outDir, { recursive: true })
writeFileSync(join(outDir, 'blocklist.json'), json)
writeFileSync(
  join(outDir, 'SOURCE.md'),
  `# Blocklist source

Generated by \`app/scripts/update-blocklist.mjs\`. Do not edit by hand.

- Sources (HTTPS):
${SOURCES.map((s) => `  - ${s}`).join('\n')}
- Downloaded: ${DOWNLOAD_DATE}
- Block rules (third-party only): ${blockList.length}
- Exception rules from lists: ${exceptList.length}
- Hard-coded never-block exceptions: ${hardRules.length}
- Total rules: ${rules.length} (cap ${MAX_RULES})
- Output size: ${json.length} bytes
- sha256 of blocklist.json: ${sha}

Only simple \`||domain^\` (optionally \`$third-party\`) and \`@@||domain^\` rules are kept; everything else is discarded.

## License and attribution

EasyList and EasyPrivacy are dual-licensed under GPLv3 and CC BY-SA 3.0.
Copyright The EasyList authors, https://easylist.to.
`,
)
console.log(JSON.stringify({ blocks: blockList.length, exceptions: exceptList.length, hard: hardRules.length, total: rules.length, bytes: json.length, sha }))
